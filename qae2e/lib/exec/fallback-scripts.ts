function sauceSpecFromCases(cases: TestCase[]): string {
  const lines: string[] = [];
  lines.push(`import { test, expect } from "../../fixtures/test.fixture";`);
  lines.push(`import { Credentials, ErrorMessages, Urls } from "../../utils/test-data";`);
  lines.push("");
  lines.push(`/** SauceDemo auth specs from coverage (${cases.length} cases). Playwright TS UI only. */`);
  lines.push(`test.describe("SauceDemo authentication", () => {`);

  const has = (re: RegExp) => cases.some((c) => re.test(c.title));

  if (has(/standard|successful login/i) || cases.length) {
    lines.push(`  test("Standard user login lands on inventory @smoke", async ({ loginPage, inventoryPage }) => {`);
    lines.push(`    await loginPage.goto();`);
    lines.push(`    await loginPage.expectLoginPageVisible();`);
    lines.push(`    await loginPage.loginAs(Credentials.STANDARD_USER, Credentials.PASSWORD);`);
    lines.push(`    await inventoryPage.expectLoaded();`);
    lines.push(`    await inventoryPage.expectProductCountAtLeast(6);`);
    lines.push(`    await inventoryPage.expectCartBadge(0);`);
    lines.push(`  });`);
    lines.push("");
  }

  if (has(/locked/i) || cases.length) {
    lines.push(`  test("Locked out user shows lockout error @smoke", async ({ loginPage }) => {`);
    lines.push(`    await loginPage.goto();`);
    lines.push(`    await loginPage.loginAs(Credentials.LOCKED_OUT_USER, Credentials.PASSWORD);`);
    lines.push(`    await loginPage.expectLoginError(ErrorMessages.LOCKED_OUT);`);
    lines.push(`    await loginPage.expectStillOnLogin();`);
    lines.push(`  });`);
    lines.push("");
  }

  if (has(/invalid/i) || cases.length) {
    lines.push(`  test("Invalid credentials show error @regression", async ({ loginPage }) => {`);
    lines.push(`    await loginPage.goto();`);
    lines.push(`    await loginPage.loginAs(Credentials.INVALID_USER, Credentials.PASSWORD);`);
    lines.push(`    await loginPage.expectLoginError(ErrorMessages.INVALID_CREDENTIALS);`);
    lines.push(`  });`);
    lines.push("");
    lines.push(`  test("Empty username shows required error @regression", async ({ loginPage, page }) => {`);
    lines.push(`    await loginPage.goto();`);
    lines.push(`    await page.getByRole("button", { name: "Login" }).click();`);
    lines.push(`    await loginPage.expectLoginError(ErrorMessages.USERNAME_REQUIRED);`);
    lines.push(`  });`);
    lines.push("");
  }

  if (has(/logout/i) || cases.length) {
    lines.push(`  test("Logout clears session and returns to login @smoke", async ({ loginPage, inventoryPage, page }) => {`);
    lines.push(`    await loginPage.goto();`);
    lines.push(`    await loginPage.loginAs(Credentials.STANDARD_USER, Credentials.PASSWORD);`);
    lines.push(`    await inventoryPage.expectLoaded();`);
    lines.push(`    await inventoryPage.logout();`);
    lines.push(`    await loginPage.expectLoginPageVisible();`);
    lines.push(`    await expect(page).toHaveURL(Urls.BASE);`);
    lines.push(`  });`);
    lines.push("");
  }

  if (has(/problem/i)) {
    lines.push(`  test("Problem user reaches inventory @regression", async ({ loginPage, inventoryPage }) => {`);
    lines.push(`    await loginPage.goto();`);
    lines.push(`    await loginPage.loginAs(Credentials.PROBLEM_USER, Credentials.PASSWORD);`);
    lines.push(`    await inventoryPage.expectLoaded();`);
    lines.push(`  });`);
    lines.push("");
  }

  if (has(/performance|glitch/i)) {
    lines.push(`  test("Performance glitch user eventually reaches inventory @regression", async ({ loginPage, inventoryPage }) => {`);
    lines.push(`    test.setTimeout(90_000);`);
    lines.push(`    await loginPage.goto();`);
    lines.push(`    await loginPage.loginAs(Credentials.PERFORMANCE_GLITCH_USER, Credentials.PASSWORD);`);
    lines.push(`    await inventoryPage.expectLoaded();`);
    lines.push(`  });`);
    lines.push("");
  }

  if (has(/responsive|mobile/i)) {
    lines.push(`  test("Login page usable on mobile viewport @regression", async ({ loginPage, inventoryPage, page }) => {`);
    lines.push(`    await page.setViewportSize({ width: 375, height: 667 });`);
    lines.push(`    await loginPage.goto();`);
    lines.push(`    await loginPage.expectLoginPageVisible();`);
    lines.push(`    await loginPage.loginAs(Credentials.STANDARD_USER, Credentials.PASSWORD);`);
    lines.push(`    await inventoryPage.expectLoaded();`);
    lines.push(`  });`);
    lines.push("");
  }

  lines.push(`});`);
  lines.push("");
  return lines.join("\n");
}

