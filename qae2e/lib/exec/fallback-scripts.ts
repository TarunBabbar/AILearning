function genericSpec(feature: string, cases: TestCase[]): string {
  const prop = `${feature.charAt(0).toLowerCase()}${feature.slice(1)}Page`;
  const tests = cases
    .slice(0, 12)
    .map((tc) => {
      const tag = tc.priority === "high" ? "@smoke" : "@regression";
      return `  test(${JSON.stringify(`${tc.title} ${tag}`)}, async ({ ${prop} }) => {
    await ${prop}.goto();
    await ${prop}.expectLoaded();
  });`;
    })
    .join("\n\n");

  return `import { test } from "../../fixtures/test.fixture";

test.describe(${JSON.stringify(`${feature} UI`)}, () => {
${tests}
});
`;
}

function inferBaseURL(coverage: Coverage): string {
  const blob = JSON.stringify(coverage);
  if (/saucedemo\.com/i.test(blob) || /saucedemo/i.test(blob)) return "https://www.saucedemo.com";
  const m = blob.match(/https?:\/\/[^\s"'\\]+/);
  return m ? m[0].replace(/\/$/, "") : "http://localhost:3000";
}

/** Build complete POM file set from coverage (never truncated). */
export function buildAutomationFiles(coverage: Coverage): Script["files"] {
  const baseURL = inferBaseURL(coverage);
  const cases = coverage.testCases || [];

  if (looksLikeSauceDemo(coverage)) {
    return [
      { path: "package.json", code: packageJson() },
      { path: "tsconfig.json", code: tsconfigJson() },
      { path: "playwright.config.ts", code: playwrightConfig(baseURL) },
      { path: "tests/pages/base.page.ts", code: basePage() },
      { path: "tests/pages/login.page.ts", code: sauceLoginPage() },
      { path: "tests/pages/inventory.page.ts", code: inventorySafe() },
      { path: "tests/pages/index.ts", code: saucePagesIndex() },
      { path: "tests/fixtures/test.fixture.ts", code: sauceFixture() },
      { path: "tests/utils/test-data.ts", code: sauceData() },
      { path: "tests/e2e/auth/login.spec.ts", code: sauceSpecFromCases(cases) },
    ];
  }

  const feature = genericFeatureName(coverage);
  const pageFile = `${feature.toLowerCase()}.page.ts`;
  return [
    { path: "package.json", code: packageJson() },
    { path: "tsconfig.json", code: tsconfigJson() },
    { path: "playwright.config.ts", code: playwrightConfig(baseURL) },
    { path: "tests/pages/base.page.ts", code: basePage() },
    { path: `tests/pages/${pageFile}`, code: genericPage(feature) },
    {
      path: "tests/pages/index.ts",
      code: `export { BasePage } from "./base.page";\nexport { ${feature}Page } from "./${feature.toLowerCase()}.page";\n`,
    },
    { path: "tests/fixtures/test.fixture.ts", code: genericFixture(feature) },
    { path: "tests/utils/test-data.ts", code: genericData(baseURL) },
    { path: `tests/e2e/${feature.toLowerCase()}/${feature.toLowerCase()}.spec.ts`, code: genericSpec(feature, cases) },
  ];
}

function inventorySafe(): string {
  return sauceInventoryPage();
}

/** Persist framework and return Script artifact. */
export function saveFallbackScripts(requirementId: string, coverage: Coverage): Script {
  const files = buildAutomationFiles(coverage);
  const script: Script = {
    id: crypto.randomUUID(),
    requirementId,
    coverageId: coverage.id,
    framework: "playwright",
    language: "typescript",
    files,
    createdAt: new Date().toISOString(),
  };
  insertOne("scripts", script);
  return script;
}
