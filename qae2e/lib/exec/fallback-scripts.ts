function looksLikeSauceDemo(coverage: Coverage): boolean {
  const blob = JSON.stringify(coverage).toLowerCase();
  return (
    blob.includes("saucedemo") ||
    blob.includes("swag labs") ||
    blob.includes("standard_user") ||
    blob.includes("secret_sauce") ||
    blob.includes("locked_out_user")
  );
}

